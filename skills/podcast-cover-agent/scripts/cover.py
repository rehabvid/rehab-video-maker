#!/usr/bin/env python3
"""Content-aware cover/thumbnail generator for Link Zag commentary videos.

The backdrop is always Singapore Marina Bay, rotated across several angles so
the channel has a recognizable visual identity without every cover looking the
same.  The topic (energy, Europe, AI, power, macro, investor) adds one
content-specific foreground object.  Text is always composited with PIL, never
generated by diffusion.

Example::

    .venv/bin/python skills/podcast-cover-agent/scripts/cover.py \
      --metadata build/ep01/youtube.zh.json \
      --out out/ep01/cover.zh.png \
      --candidates 3

    # Text-only preview using an existing background:
    .venv/bin/python skills/podcast-cover-agent/scripts/cover.py \
      --metadata build/ep01/youtube.zh.json \
      --background assets/marina-bay.jpg \
      --out out/ep01/cover-preview.png
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
CONFIG = ROOT / "skills" / "podcast-cover-agent" / "config" / "cover-styles.json"
ENGINE = ROOT / "tools" / "gen" / "cover.py"
SHARED = ROOT / "skills" / "podcast-avatar-commentary" / "scripts"
if str(SHARED) not in sys.path:
    sys.path.insert(0, str(SHARED))

from lib import contains_cjk, find_font  # noqa: E402


def _load(path: Path) -> dict:
    data = json.loads(path.read_text())
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected a JSON object")
    return data


def _score(text: str, words: list[str]) -> int:
    score = 0
    for word in words:
        word = word.lower().strip()
        if not word:
            continue
        if re.search(r"[a-z0-9]", word):
            if re.search(r"(?<![a-z0-9])" + re.escape(word) + r"(?![a-z0-9])", text):
                score += 3
        elif word in text:
            score += 3
    return score


def _topic(metadata: dict, config: dict, override: str | None) -> tuple[str, dict]:
    if override:
        return override, config["topics"][override]
    cover = metadata.get("cover") or {}
    if cover.get("topic") and cover["topic"] in config["topics"]:
        return cover["topic"], config["topics"][cover["topic"]]
    sample = " ".join([
        str(metadata.get("title") or ""),
        " ".join(str(x) for x in metadata.get("tags") or []),
        str(metadata.get("description") or ""),
        " ".join(
            str(ch.get("title") or "")
            for ch in metadata.get("chapters") or []
        ),
    ]).lower()
    scored = [
        (_score(sample, item.get("keywords") or []), name, item)
        for name, item in config["topics"].items()
        if name != "default"
    ]
    scored.sort(key=lambda item: item[0], reverse=True)
    if scored and scored[0][0] > 0:
        return scored[0][1], scored[0][2]
    return "default", config["topics"]["default"]


def _angle(metadata: dict, config: dict, override: str | None) -> dict:
    angles = config["angles"]
    if override:
        for angle in angles:
            if angle["id"] == override:
                return angle
        raise ValueError(f"unknown angle {override!r}; choose {', '.join(a['id'] for a in angles)}")
    cover = metadata.get("cover") or {}
    requested = cover.get("angle")
    if requested:
        for angle in angles:
            if angle["id"] == requested:
                return angle
    seed_text = str(metadata.get("title") or "cover")
    index = int(hashlib.sha1(seed_text.encode("utf-8")).hexdigest()[:8], 16) % len(angles)
    return angles[index]


def _stat(metadata: dict, cover: dict, override: str | None) -> str:
    if override:
        return override
    if cover.get("stat"):
        return str(cover["stat"])
    text = " ".join([
        str(metadata.get("title") or ""),
        str(metadata.get("description") or ""),
    ])
    match = re.search(r"\d+(?:\.\d+)?\s*[-–—]\s*\d+(?:\.\d+)?\s*%", text)
    if match:
        return match.group(0).replace(" ", "")
    match = re.search(r"\d+(?:\.\d+)?\s*%", text)
    return match.group(0).replace(" ", "") if match else ""


def _prompt(topic: dict, angle: dict, render_style: dict) -> str:
    foreground = str(topic.get("foreground") or "").strip()
    parts = [
        render_style["prefix"],
        angle["prompt"],
        foreground,
        "premium financial magazine cover, one focal point, no people, no text, no logos, 16:9",
    ]
    return ", ".join(part for part in parts if part)


def _contact_sheet(paths: list[Path], out: Path, labels: list[str]) -> Path:
    thumb_w, thumb_h = 480, 270
    pad = 18
    label_h = 34
    cols = min(3, len(paths))
    rows = (len(paths) + cols - 1) // cols
    sheet = Image.new("RGB", (cols * (thumb_w + pad) + pad, rows * (thumb_h + label_h + pad) + pad), (16, 18, 22))
    draw = ImageDraw.Draw(sheet)
    font = find_font(20)
    for i, (path, label) in enumerate(zip(paths, labels)):
        with Image.open(path) as raw:
            image = raw.convert("RGB").resize((thumb_w, thumb_h), Image.LANCZOS)
        x = pad + (i % cols) * (thumb_w + pad)
        y = pad + (i // cols) * (thumb_h + label_h + pad)
        sheet.paste(image, (x, y))
        draw.text((x, y + thumb_h + 6), label, font=font, fill=(230, 230, 230))
    sheet.save(out, "PNG")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metadata", help="youtube.zh.json or youtube.json")
    parser.add_argument("--slides", help="optional slides.json for extra context")
    parser.add_argument("--out", required=True)
    parser.add_argument("--title", help="override title")
    parser.add_argument("--stat", help="override the big number")
    parser.add_argument("--subtitle")
    parser.add_argument("--kicker")
    parser.add_argument("--topic", help="topic id from cover-styles.json")
    parser.add_argument("--render-style", choices=["sketch", "photo"], default=None)
    parser.add_argument("--angle", help="angle id from cover-styles.json")
    parser.add_argument("--candidates", type=int, default=None)
    parser.add_argument("--seed", type=int, default=None)
    parser.add_argument("--steps", type=int, default=None)
    parser.add_argument("--cfg", type=float, default=None)
    parser.add_argument("--background", help="skip generation and use this image")
    parser.add_argument("--no-generate", action="store_true", help="require --background")
    parser.add_argument("--reference", help="optional IPAdapter style reference")
    parser.add_argument("--comfy-url", default="http://127.0.0.1:8188")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--contact-sheet", action="store_true", default=True)
    args = parser.parse_args(argv)

    config = _load(CONFIG)
    args.topic = None if not args.topic else args.topic
    # argparse cannot know the config choices; validate after loading.
    if args.topic and args.topic not in config["topics"]:
        parser.error(f"unknown topic {args.topic!r}; choose {', '.join(config['topics'])}")
    metadata = _load(Path(args.metadata)) if args.metadata else {}
    cover = metadata.get("cover") or {}
    if args.slides:
        slides = _load(Path(args.slides))
        metadata = {
            **metadata,
            "description": str(metadata.get("description") or "")
            + " "
            + " ".join(str(s.get("heading") or "") for s in slides.get("shots", [])),
        }
    topic_id, topic = _topic(metadata, config, args.topic)
    render_id = args.render_style or cover.get("render_style") or config["defaults"]["render_style"]
    if render_id not in config["render_styles"]:
        parser.error(f"unknown render style {render_id!r}")
    render_style = config["render_styles"][render_id]
    angle = _angle(metadata, config, args.angle)
    title = args.title or cover.get("title") or metadata.get("title") or "Independent commentary"
    title = str(title).split("|")[0].strip()
    language = "zh-Hans" if contains_cjk(title) else "en"
    kicker = args.kicker or cover.get("kicker") or topic.get(f"kicker_{'zh' if language.startswith('zh') else 'en'}") or topic["label"]
    subtitle = args.subtitle or cover.get("subtitle") or ("独立评论" if language.startswith("zh") else "Independent commentary")
    stat = _stat(metadata, cover, args.stat)
    prompt = _prompt(topic, angle, render_style)
    defaults = config["defaults"]
    candidates = max(1, int(args.candidates or cover.get("candidates") or defaults["candidates"]))
    seed = int(args.seed if args.seed is not None else cover.get("seed") or defaults["seed_base"])
    steps = int(args.steps or cover.get("steps") or defaults["steps"])
    cfg = float(args.cfg if args.cfg is not None else cover.get("cfg") or defaults["cfg"])
    negative = defaults["negative"]
    if render_style.get("negative_extra"):
        negative += ", " + render_style["negative_extra"]

    print(json.dumps({
        "topic": topic_id,
        "render_style": render_id,
        "angle": angle["id"],
        "title": title,
        "stat": stat,
        "subtitle": subtitle,
        "kicker": kicker,
        "prompt": prompt,
        "negative": negative,
        "seed": seed,
        "candidates": candidates,
    }, ensure_ascii=False, indent=2))
    if args.dry_run:
        return 0
    if args.no_generate and not args.background:
        parser.error("--no-generate requires --background")

    out = Path(args.out).expanduser()
    out.parent.mkdir(parents=True, exist_ok=True)
    outputs: list[Path] = []
    for index in range(candidates):
        candidate_seed = seed + index * 37
        candidate_out = out if index == 0 else out.with_name(f"{out.stem}-{index + 1}{out.suffix}")
        cmd = [
            sys.executable, str(ENGINE),
            "--title", title,
            "--stat", stat,
            "--subtitle", subtitle,
            "--kicker", kicker,
            "--prompt", prompt,
            "--negative", negative,
            "--theme", render_style.get("theme", "dark"),
            "--out", str(candidate_out),
            "--width", str(defaults["width"]),
            "--height", str(defaults["height"]),
            "--steps", str(steps),
            "--cfg", str(cfg),
            "--seed", str(candidate_seed),
            "--comfy-url", args.comfy_url,
        ]
        if args.background:
            cmd += ["--background", str(Path(args.background).expanduser())]
        if args.reference:
            cmd += ["--reference", str(Path(args.reference).expanduser())]
        print("+ " + " ".join(cmd), flush=True)
        result = subprocess.run(cmd, cwd=ROOT)
        if result.returncode:
            return result.returncode
        outputs.append(candidate_out)

    manifest = {
        "topic": topic_id,
        "render_style": render_id,
        "angle": angle["id"],
        "title": title,
        "stat": stat,
        "subtitle": subtitle,
        "kicker": kicker,
        "prompt": prompt,
        "negative": negative,
        "seed": seed,
        "candidates": [str(path) for path in outputs],
    }
    (out.with_suffix(".json")).write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    if args.contact_sheet and len(outputs) > 1:
        sheet = out.with_name(f"{out.stem}-contact{out.suffix}")
        _contact_sheet(
            outputs,
            sheet,
            [f"{render_id} · {angle['id']} · seed {seed + i * 37}" for i in range(len(outputs))],
        )
        print(f"contact sheet: {sheet}")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
